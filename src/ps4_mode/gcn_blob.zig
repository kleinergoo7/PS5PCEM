test "parses a real captured vertex shader blob" {
    const blob = try parse(&vs_blob);
    try std.testing.expectEqual(Stage.vertex, blob.stage);
    try std.testing.expectEqualStrings("vs", blob.stage.label());
    try std.testing.expectEqual(@as(u32, 0x104), blob.isa_offset);
    try std.testing.expectEqual(@as(u32, 88), blob.isa_size); // 22 dwords
    const isa = isaBytes(&vs_blob, blob);
    try std.testing.expectEqual(@as(usize, 88), isa.len);
    try std.testing.expectEqual(@as(u32, 0xbeeb03ff), std.mem.readInt(u32, isa[0..4], .little));
    try std.testing.expectEqual(@as(u32, 0xbf810000), std.mem.readInt(u32, isa[isa.len - 4 ..][0..4], .little));
}

test "rejects non-blobs" {
    var zeros: [64]u8 = [_]u8{0} ** 64;
    try std.testing.expectError(Error.BadMagic, parse(&zeros));
    @memcpy(zeros[0..magic.len], magic);
    try std.testing.expectError(Error.UnknownStage, parse(&zeros));
}

//! Reader for real PS4 "OrbShdr" GCN shader blobs.
//!
//! Terraria's shader blobs begin with the eight bytes `OrbShdr\x07`. The
//! graphics stage is a u16 at offset 14 (8 = vertex, 12 = pixel). An inner
//! `Shdr` header follows; the GCN ISA starts with the 0xbeeb03ff prolog dword
//! and ends with an `s_endpgm` (0xbf810000) dword. The existing gcn_header
//! module describes a simplified layout that does not match shipped blobs,
//! so this reader locates the ISA by its markers instead of trusting offsets.

const std = @import("std");

pub const Error = error{
    Truncated,
    BadMagic,
    UnknownStage,
    NoInnerHeader,
    NoIsa,
};

pub const Stage = enum {
    vertex,
    pixel,

    pub fn label(self: Stage) []const u8 {
        return switch (self) {
            .vertex => "vs",
            .pixel => "ps",
        };
    }
};

/// A parsed real shader blob. Offsets are byte offsets from the blob start.
pub const Blob = struct {
    stage: Stage,
    /// Offset of the first ISA dword (the prolog marker).
    isa_offset: u32,
    /// ISA size in bytes, including s_endpgm.
    isa_size: u32,
};

const magic = "OrbShdr\x07";
const inner_magic = "Shdr\x07\x00\x01\x00";
const isa_prolog = "\xff\x03\xeb\xbe"; // 0xbeeb03ff
const isa_end = "\x00\x00\x81\xbf"; // s_endpgm, 0xbf810000

pub fn parse(bytes: []const u8) Error!Blob {
    if (bytes.len < magic.len + 8) return Error.Truncated;
    if (!std.mem.eql(u8, bytes[0..magic.len], magic)) return Error.BadMagic;

    const stage_field = std.mem.readInt(u16, bytes[14..16], .little);
    const stage: Stage = switch (stage_field) {
        8 => .vertex,
        12 => .pixel,
        else => return Error.UnknownStage,
    };

    const inner = std.mem.indexOfPos(u8, bytes, magic.len, inner_magic) orelse return Error.NoInnerHeader;
    const prolog = std.mem.indexOfPos(u8, bytes, inner + inner_magic.len, isa_prolog) orelse return Error.NoIsa;
    const end = std.mem.indexOfPos(u8, bytes, prolog + isa_prolog.len, isa_end) orelse return Error.NoIsa;
    if (end < prolog) return Error.NoIsa;

    return .{
        .stage = stage,
        .isa_offset = @intCast(prolog),
        .isa_size = @intCast(end + isa_end.len - prolog),
    };
}

/// Slice out the GCN ISA described by a parsed blob.
pub fn isaBytes(bytes: []const u8, blob: Blob) []const u8 {
    return bytes[blob.isa_offset .. blob.isa_offset + blob.isa_size];
}

